"""
build_fonts.py - generate fb-doc-fonts.css for the paperwork POC.

Fishbowl's Jasper paperwork is set entirely in Open Sans, which the client
ships in lib/open-sans-1.0.jar (Apache-2.0). Embedding the same font in the HTML
replica makes text widths, and therefore page breaks, identical on every machine,
with no dependency on a font CDN (on-prem customers often block them).

The three faces are subset to Latin, Latin-1, Latin Extended-A, punctuation and
currency symbols, converted to woff2 and written as base64 @font-face rules.

Usage:  python build_fonts.py [path-to-open-sans-jar]
Needs:  pip install fonttools brotli
"""
import base64
import io
import os
import sys
import zipfile

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'fb-doc-fonts.css')
JAR = sys.argv[1] if len(sys.argv) > 1 else r'C:\Program Files\Fishbowl\lib\open-sans-1.0.jar'

FACES = [
    ('fonts/OpenSans-Regular.ttf', 'normal', 400),
    ('fonts/OpenSans-Bold.ttf',    'normal', 700),
    ('fonts/OpenSans-Italic.ttf',  'italic', 400),
]

# Latin, Latin-1, Latin Extended-A, general punctuation, currency, a few symbols.
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
    list(range(0x2010, 0x2028)) + list(range(0x2030, 0x203B)) +
    list(range(0x20A0, 0x20C0)) + [0x2116, 0x2122, 0x2212, 0x2022, 0x2026]
)


def subset_face(data):
    font = TTFont(io.BytesIO(data))
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'tnum', 'lnum']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(options=opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return buf.getvalue()


def main():
    out = [
        '/* fb-doc-fonts.css - GENERATED by tools/build_fonts.py; do not edit.',
        '   Open Sans (Apache License 2.0) from Fishbowl\'s lib/open-sans-1.0.jar,',
        '   subset to Latin + Latin-1 + Latin Ext-A + punctuation + currency, woff2.',
        '   Family name "FB Doc Open Sans" so it never collides with an installed copy. */',
    ]
    with zipfile.ZipFile(JAR) as jar:
        for name, style, weight in FACES:
            woff2 = subset_face(jar.read(name))
            b64 = base64.b64encode(woff2).decode('ascii')
            out.append(
                "@font-face{font-family:'FB Doc Open Sans';font-style:%s;font-weight:%d;"
                "font-display:block;src:url(data:font/woff2;base64,%s) format('woff2');}"
                % (style, weight, b64))
            print('%-28s %7d bytes woff2' % (name, len(woff2)))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(OUT), os.path.getsize(OUT), 'bytes')


if __name__ == '__main__':
    main()
